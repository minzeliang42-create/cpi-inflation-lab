assert.ok(dist.validDistributionBounds('-2','5'));assert.ok(!dist.validDistributionBounds('','5'));assert.ok(!dist.validDistributionBounds('5','2'));assert.ok(!dist.validDistributionBounds('NaN','2'));assert.ok(!dist.validDistributionBounds('Infinity','2'));
