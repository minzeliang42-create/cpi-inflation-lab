import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('web/app.js','utf8');
const helper=source.slice(source.indexOf('let CARD_ESTIMATES='),source.indexOf('async function load()'));
const ctx=vm.createContext({LABEL:{headline:'Headline',core:'Core'},fmt:v=>v==null?'NA':v.toFixed(2),DATA:{meta:{version:'v'}}});
vm.runInContext(helper,ctx);
const rows=[{month:'2026-09',headline:3.737684729},{month:'2026-10',headline:null}];
ctx.rows=rows;
vm.runInContext(`CARD_ESTIMATES={historical_version:'v',estimates:{headline:{month:'2026-10',status:'estimated',estimated_yoy:4.022111815}}}`,ctx);
assert.match(vm.runInContext(`latestCard('headline',rows,'%','measures')`,ctx),/4.02/);
assert.match(vm.runInContext(`latestCard('headline',rows,'%','measures')`,ctx),/3.74/);
assert.match(vm.runInContext(`latestCard('headline',rows,'%','measures')`,ctx),/非官方/);
assert.doesNotMatch(vm.runInContext(`latestCard('headline',rows,'pp','acceleration')`,ctx),/4.02/);
vm.runInContext(`CARD_ESTIMATES.historical_version='old'`,ctx);
assert.equal(vm.runInContext(`cardEstimate('headline',rows,'v')`,ctx),null);
vm.runInContext(`CARD_ESTIMATES.historical_version='v';rows[1].headline=4.1`,ctx);
assert.equal(vm.runInContext(`cardEstimate('headline',rows,'v')`,ctx),null);
console.log('Card display: isolated, official precedence and stale-version rejection PASS');
